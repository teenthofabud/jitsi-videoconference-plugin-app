#!/usr/bin/env node
// Writes the build-specific parts of nginx's Content-Security-Policy as an nginx
// snippet that the Dockerfile copies next to the server config:
//
// - $csp_script_hashes: pre-rendered pages carry inline scripts Angular injects
//   for event replay (the jsaction dispatch contract and its bootstrap call),
//   and optimized builds load the stylesheet with an inline
//   onload="this.media='all'" handler after inlining critical CSS. script-src
//   only allows 'self', so it needs the hash of each or the browser blocks them.
// - $csp_cdn_origin and $csp_api_origin: the CDN serving the favicon and
//   images, and the API the app calls, both of which differ per environment.
//   They're read back from the pre-rendered home page (the favicon link and
//   SeoService's API preconnect) so src/environments/environment.<env>.ts stays
//   the single source of truth.

import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const distDir = 'dist/toab-jitsi-website';
const browserDir = path.join(distDir, 'browser');

function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return entry.name === 'assets' ? [] : htmlFiles(full);
    return entry.name.endsWith('.html') ? [full] : [];
  });
}

// Only scripts the browser executes: no src, and no type or a JavaScript type.
// Data blocks (ng-state JSON, ld+json structured data) are not subject to CSP.
const executable = /^(|text\/javascript|application\/javascript|module)$/i;

const sha256 = (code) => `'sha256-${createHash('sha256').update(code, 'utf8').digest('base64')}'`;

// Attribute values are hashed as the browser sees them, after entity decoding.
const decodeEntities = (value) =>
  value.replace(/&quot;/g, '"').replace(/&#39;|&apos;/g, "'").replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');

const hashes = new Set();
const handlerHashes = new Set();
for (const file of htmlFiles(browserDir)) {
  const html = readFileSync(file, 'utf8');
  for (const [, attrs, body] of html.matchAll(/<script\b([^>]*)>([\s\S]*?)<\/script>/gi)) {
    if (/\bsrc=/i.test(attrs) || !body) continue;
    const type = attrs.match(/\btype=["']?([^"'\s>]*)/i)?.[1] ?? '';
    if (!executable.test(type)) continue;
    hashes.add(sha256(body));
  }
  // Inline event handlers (onload=, onerror=, ...). Requires whitespace before
  // the name so jsaction's on="click:;" bookkeeping attribute isn't picked up.
  for (const [, doubleQuoted, singleQuoted] of html.matchAll(/\son[a-z]+=(?:"([^"]*)"|'([^']*)')/gi)) {
    handlerHashes.add(sha256(decodeEntities(doubleQuoted ?? singleQuoted)));
  }
}

// Handler hashes only take effect alongside 'unsafe-hashes', which still
// restricts handlers to exactly these bodies; it isn't added unless needed.
const sources = [...[...hashes].sort(), ...(handlerHashes.size ? ["'unsafe-hashes'", ...[...handlerHashes].sort()] : [])];

const indexHtml = readFileSync(path.join(browserDir, 'index.html'), 'utf8');
function originOf(linkPattern, what) {
  const href = indexHtml.match(linkPattern)?.[1];
  if (!href) {
    throw new Error(`No ${what} link in pre-rendered index.html; is SeoService running during pre-rendering?`);
  }
  return new URL(href).origin;
}
const cdnOrigin = originOf(/<link[^>]*rel="icon"[^>]*href="([^"]+)"/, 'favicon');
const apiOrigin = originOf(/<link[^>]*id="api-preconnect"[^>]*href="([^"]+)"/, 'API preconnect');

const nginxDir = path.join(distDir, 'nginx');
mkdirSync(nginxDir, { recursive: true });
writeFileSync(
  path.join(nginxDir, 'csp-sources.conf'),
  [
    '# Generated by scripts/csp-sources.mjs; do not edit.',
    `set $csp_script_hashes "${sources.join(' ')}";`,
    `set $csp_cdn_origin "${cdnOrigin}";`,
    `set $csp_api_origin "${apiOrigin}";`,
    '',
  ].join('\n')
);

console.log(`CSP sources generated: ${hashes.size} inline script(s), ${handlerHashes.size} inline event handler(s), CDN ${cdnOrigin}, API ${apiOrigin}`);
